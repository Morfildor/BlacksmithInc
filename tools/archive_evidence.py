#!/usr/bin/env python3
"""Owner decision E (review 2026-10-14): bulky evidence images leave the tracked tree, archived first, history untouched.

  python tools/archive_evidence.py                     # writes docs/EVIDENCE_INDEX.md: what is kept, what would be archived
  python tools/archive_evidence.py --archive DIR       # zips every image not in the reference set into DIR, one zip per
                                                       # evidence folder, with MANIFEST.sha256; verifies each zip against git
  python tools/archive_evidence.py --archive DIR --remove   # the same, then `git rm` the archived images (no commit)

The reference set stays in the tree: every image a tracked Markdown file names, and the current review's device
captures (docs/review_2026-10-14/device). Nothing is deleted from history: every archived path stays retrievable with
`git checkout <commit> -- <path>` from the commit the index names. Run --remove only where DIR survives (the owner's
machine), never in a disposable container.
"""
import argparse
import hashlib
import os
import re
import subprocess
import sys
import zipfile
from collections import defaultdict

ROOT = subprocess.check_output(["git", "rev-parse", "--show-toplevel"], text=True).strip()
IMAGE = re.compile(r"\.(png|jpe?g|webp|gif)$", re.I)
ALWAYS_KEEP = ("docs/review_2026-10-14/device/",)


def git(*args):
    return subprocess.check_output(["git", *args], cwd=ROOT, text=True)


def tracked():
    return [f for f in git("ls-files").splitlines() if f]


def reference_set(files):
    text = ""
    for f in files:
        if f.endswith(".md"):
            with open(os.path.join(ROOT, f), encoding="utf-8", errors="ignore") as h:
                text += h.read() + "\n"
    images = [f for f in files if f.startswith("docs/") and IMAGE.search(f)]
    keep = {f for f in images if f.startswith(ALWAYS_KEEP) or f in text or f[len("docs/"):] in text or os.path.basename(f) in text}
    return images, keep


def folder(path):
    """The evidence folder an image belongs to: the first two levels under docs/ ("docs/run_variety_evidence/screens2")."""
    parts = path.split("/")
    return "/".join(parts[:3]) if len(parts) > 3 else "/".join(parts[:2])


def blob_sha256(path):
    data = subprocess.check_output(["git", "show", f"HEAD:{path}"], cwd=ROOT)
    return hashlib.sha256(data).hexdigest()


def write_index(images, keep, commit):
    archived = [f for f in images if f not in keep]
    groups = defaultdict(lambda: [0, 0, 0])
    for f in images:
        g = groups[folder(f)]
        g[0] += 1
        g[1] += os.path.getsize(os.path.join(ROOT, f))
        if f in keep:
            g[2] += 1
    mb = lambda b: f"{b / 1048576:.1f}"
    lines = [
        "# Evidence index (owner decision E)",
        "",
        "Generated by `tools/archive_evidence.py`. Bulky evidence images leave the tracked tree after they are archived; "
        "the reference set below stays. Nothing is removed from history: every archived image is retrievable with "
        f"`git checkout {commit} -- <path>`.",
        "",
        f"Images under `docs/`: {len(images)} ({mb(sum(os.path.getsize(os.path.join(ROOT, f)) for f in images))} MB). "
        f"Reference set kept: {len(keep)} ({mb(sum(os.path.getsize(os.path.join(ROOT, f)) for f in keep))} MB): every image a "
        "tracked Markdown file names, and `docs/review_2026-10-14/device/`. To archive: "
        f"{len(archived)} ({mb(sum(os.path.getsize(os.path.join(ROOT, f)) for f in archived))} MB), one zip per folder.",
        "",
        "| Folder | Images | MB | Kept | Archive |",
        "|---|---|---|---|---|",
    ]
    for name in sorted(groups):
        n, b, k = groups[name]
        zip_name = name.replace("docs/", "").replace("/", "__") + ".zip" if k < n else ""
        lines.append(f"| `{name}` | {n} | {mb(b)} | {k} | {zip_name} |")
    lines += ["", "## Kept", ""] + [f"- `{f}`" for f in sorted(keep)] + [""]
    with open(os.path.join(ROOT, "docs/EVIDENCE_INDEX.md"), "w", encoding="utf-8") as h:
        h.write("\n".join(lines))
    return archived


def archive(archived, out):
    os.makedirs(out, exist_ok=True)
    by = defaultdict(list)
    for f in archived:
        by[folder(f)].append(f)
    manifest = []
    for name, fs in sorted(by.items()):
        zip_path = os.path.join(out, name.replace("docs/", "").replace("/", "__") + ".zip")
        with zipfile.ZipFile(zip_path, "w", zipfile.ZIP_DEFLATED) as z:
            for f in fs:
                z.write(os.path.join(ROOT, f), f)
        # Verify: every entry reads back and matches the bytes git holds at HEAD.
        with zipfile.ZipFile(zip_path) as z:
            if z.testzip() is not None:
                sys.exit(f"{zip_path} is damaged")
            for f in fs:
                got = hashlib.sha256(z.read(f)).hexdigest()
                if got != blob_sha256(f):
                    sys.exit(f"{zip_path}: {f} does not match git")
                manifest.append(f"{got}  {f}  {os.path.basename(zip_path)}")
        print(f"archived {len(fs):4d} images to {zip_path}")
    with open(os.path.join(out, "MANIFEST.sha256"), "w") as h:
        h.write("\n".join(manifest) + "\n")
    return manifest


def main():
    p = argparse.ArgumentParser()
    p.add_argument("--archive", metavar="DIR")
    p.add_argument("--remove", action="store_true")
    a = p.parse_args()
    if a.remove and not a.archive:
        sys.exit("--remove needs --archive DIR: nothing leaves the tree before it is archived")
    commit = git("rev-parse", "--short", "HEAD").strip()
    images, keep = reference_set(tracked())
    archived = write_index(images, keep, commit)
    print(f"index: {len(images)} images, keep {len(keep)}, archive {len(archived)} (docs/EVIDENCE_INDEX.md)")
    if a.archive:
        manifest = archive(archived, os.path.abspath(a.archive))
        if a.remove:
            if len(manifest) != len(archived):
                sys.exit("archive incomplete: nothing removed")
            subprocess.check_call(["git", "rm", "-q", "--", *archived], cwd=ROOT)
            print(f"git rm {len(archived)} images; review and commit when ready")


if __name__ == "__main__":
    main()
